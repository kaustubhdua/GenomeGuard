-- Event records used by the authenticated request/review/consent RPCs.
-- The table is server-only; the browser cannot read or mutate it directly.
create table if not exists genomeguard.api_events (
  id bigint generated by default as identity primary key,
  auth_user_id uuid,
  event_type text not null check (length(trim(event_type)) between 1 and 120),
  request_id bigint,
  outcome text not null default 'recorded' check (length(trim(outcome)) between 1 and 120),
  details jsonb not null default '{}'::jsonb check (jsonb_typeof(details)='object'),
  created_at timestamptz not null default now()
);
create index if not exists api_events_request_created
  on genomeguard.api_events(request_id, created_at desc)
  where request_id is not null;
create index if not exists api_events_actor_created
  on genomeguard.api_events(auth_user_id, created_at desc)
  where auth_user_id is not null;
alter table genomeguard.api_events enable row level security;
revoke all on table genomeguard.api_events from public, anon, authenticated, service_role;
comment on table genomeguard.api_events is
  'Server-only security and request lifecycle events. Never store raw genotypes, credentials, or unnecessary personal information here.';
