-- Supabase-native request API foundation for GenomeGuard.
-- All application objects remain in the private genomeguard schema.
ALTER TABLE genomeguard.requesters
  ADD COLUMN IF NOT EXISTS auth_user_id uuid;
CREATE UNIQUE INDEX IF NOT EXISTS requesters_auth_user_id_unique
  ON genomeguard.requesters(auth_user_id)
  WHERE auth_user_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS genomeguard.api_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id uuid,
  event_type text NOT NULL,
  request_id bigint,
  outcome text NOT NULL DEFAULT 'recorded',
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE genomeguard.api_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON genomeguard.api_events FROM anon, authenticated, service_role;
REVOKE ALL ON genomeguard.requesters FROM anon, authenticated, service_role;
REVOKE ALL ON genomeguard.requests FROM anon, authenticated, service_role;
REVOKE ALL ON genomeguard.decisions FROM anon, authenticated, service_role;
REVOKE ALL ON genomeguard.audit_log FROM anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.gg_submit_request(
  p_auth_user_id uuid, p_name text, p_institution text, p_purpose text,
  p_disease text, p_is_commercial boolean, p_data_level text,
  p_cohort_filter jsonb, p_variant_filter jsonb
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_requester_id bigint; v_request_id bigint;
BEGIN
  IF p_auth_user_id IS NULL
     OR p_purpose IS NULL OR length(btrim(p_purpose)) < 3 OR length(p_purpose) > 500
     OR p_data_level NOT IN ('aggregate', 'frequency', 'variant', 'individual')
     OR length(coalesce(p_name,'')) < 2 OR length(p_name) > 120
     OR length(coalesce(p_institution,'')) < 2 OR length(p_institution) > 200 THEN
    RAISE EXCEPTION 'invalid_request' USING ERRCODE = '22023';
  END IF;
  INSERT INTO genomeguard.requesters(auth_user_id,name,role,credential_level,institution,created_at)
  VALUES (p_auth_user_id,btrim(p_name),'researcher','registered',btrim(p_institution),now()::text)
  ON CONFLICT (auth_user_id) WHERE auth_user_id IS NOT NULL
  DO UPDATE SET name=EXCLUDED.name,institution=EXCLUDED.institution
  RETURNING id INTO v_requester_id;
  INSERT INTO genomeguard.requests(
    requester_id,ts,purpose,disease,is_commercial,data_level,
    cohort_filter_json,variant_filter_json,status
  ) VALUES (
    v_requester_id,now()::text,btrim(p_purpose),nullif(btrim(coalesce(p_disease,'')),''),
    CASE WHEN p_is_commercial THEN 1 ELSE 0 END,p_data_level,
    coalesce(p_cohort_filter,'{}'::jsonb)::text,coalesce(p_variant_filter,'{}'::jsonb)::text,
    'pending_review'
  ) RETURNING id INTO v_request_id;
  INSERT INTO genomeguard.api_events(auth_user_id,event_type,request_id,outcome,details)
  VALUES (p_auth_user_id,'research_request_submitted',v_request_id,'pending_review',
    jsonb_build_object('data_level',p_data_level,'commercial',p_is_commercial));
  RETURN jsonb_build_object('id',v_request_id,'status','pending_review',
    'message','Request stored for steward review. No data access has been granted.');
END;
$$;

CREATE OR REPLACE FUNCTION public.gg_list_my_requests(p_auth_user_id uuid)
RETURNS jsonb LANGUAGE sql SECURITY DEFINER SET search_path = ''
AS $$
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'id',q.id,'created_at',q.ts,'purpose',q.purpose,'disease',q.disease,
    'is_commercial',(q.is_commercial=1),'data_level',q.data_level,'status',q.status,
    'outcome',d.outcome,'needs_human',coalesce(d.needs_human,1)=1
  ) ORDER BY q.id DESC),'[]'::jsonb)
  FROM genomeguard.requests q
  JOIN genomeguard.requesters r ON r.id=q.requester_id
  LEFT JOIN genomeguard.decisions d ON d.request_id=q.id
  WHERE r.auth_user_id=p_auth_user_id;
$$;
REVOKE ALL ON FUNCTION public.gg_submit_request(uuid,text,text,text,text,boolean,text,jsonb,jsonb) FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.gg_list_my_requests(uuid) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.gg_submit_request(uuid,text,text,text,text,boolean,text,jsonb,jsonb) TO service_role;
GRANT EXECUTE ON FUNCTION public.gg_list_my_requests(uuid) TO service_role;
