-- Preserve every steward review, even when a request is sent back for more information and reviewed again.
create table if not exists genomeguard.request_review_history (
  id bigint generated by default as identity primary key,
  request_id bigint not null references genomeguard.requests(id) on delete restrict,
  organization_id uuid not null references genomeguard.organizations(id) on delete restrict,
  reviewer_auth_user_id uuid not null,
  previous_status text not null check (previous_status in ('pending_review','needs_more_information')),
  outcome text not null check (outcome in ('approved','denied','needs_more_information')),
  reason text not null check (length(trim(reason)) between 3 and 2000),
  decision_id bigint not null references genomeguard.decisions(id) on delete restrict,
  created_at timestamptz not null default now()
);
create index if not exists request_review_history_request_created
  on genomeguard.request_review_history(request_id, created_at, id);
alter table genomeguard.request_review_history enable row level security;
revoke all on table genomeguard.request_review_history from public, anon, authenticated, service_role;
comment on table genomeguard.request_review_history is
  'Append-only history of each human review transition. Direct table access is server-only; review events are exposed only through the authorized request-detail RPC.';

create or replace function public.gg_review_request(
  p_auth_user_id uuid,
  p_request_id bigint,
  p_outcome text,
  p_reason text
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $review$
declare
  v_membership genomeguard.organization_memberships%rowtype;
  v_request genomeguard.requests%rowtype;
  v_decision_id bigint;
  v_status text;
begin
  if p_auth_user_id is null or p_request_id is null
     or p_outcome not in ('approved','denied','needs_more_information')
     or p_reason is null or length(btrim(p_reason)) < 3 or length(btrim(p_reason)) > 2000 then
    raise exception 'invalid_review' using errcode = '22023';
  end if;

  select m.* into v_membership
  from genomeguard.organization_memberships m
  join genomeguard.organizations o on o.id=m.organization_id
  where m.auth_user_id=p_auth_user_id and m.status='active' and o.status='active'
    and m.role in ('reviewer','organization_admin')
  order by m.organization_id
  limit 1;
  if not found then
    raise exception 'active_reviewer_membership_required' using errcode = '42501';
  end if;

  select * into v_request from genomeguard.requests
    where id=p_request_id and organization_id=v_membership.organization_id
    for update;
  if not found then
    raise exception 'request_not_found' using errcode = 'P0002';
  end if;
  if v_request.status not in ('pending_review','needs_more_information') then
    raise exception 'request_not_reviewable' using errcode = '55000';
  end if;

  insert into genomeguard.decisions(request_id,outcome,reasons_json,explanation_text,
      needs_human,reviewed_by,reviewed_at)
  values (p_request_id,p_outcome,jsonb_build_array(btrim(p_reason))::text,btrim(p_reason),
      0,p_auth_user_id::text,now()::text)
  on conflict (request_id) do update set outcome=excluded.outcome,
      reasons_json=excluded.reasons_json, explanation_text=excluded.explanation_text,
      needs_human=0, reviewed_by=excluded.reviewed_by, reviewed_at=excluded.reviewed_at
  returning id into v_decision_id;

  insert into genomeguard.request_review_history(
      request_id,organization_id,reviewer_auth_user_id,previous_status,outcome,reason,decision_id
  ) values (
      p_request_id,v_request.organization_id,p_auth_user_id,v_request.status,p_outcome,btrim(p_reason),v_decision_id
  );

  v_status := case when p_outcome='needs_more_information' then 'needs_more_information'
                   when p_outcome='approved' then 'approved_pending_release'
                   else 'denied' end;
  update genomeguard.requests set status=v_status where id=p_request_id;

  insert into genomeguard.api_events(auth_user_id,event_type,request_id,outcome,details)
  values (p_auth_user_id,'research_request_reviewed',p_request_id,p_outcome,
    jsonb_build_object('decision_id',v_decision_id,'reason',btrim(p_reason),
      'organization_id',v_membership.organization_id,'previous_status',v_request.status,
      'new_status',v_status));

  return jsonb_build_object('request_id',p_request_id,'decision_id',v_decision_id,
    'outcome',p_outcome,'status',v_status,
    'message','Review decision recorded. Approval does not itself release genomic data.');
end;
$review$;
revoke all on function public.gg_review_request(uuid,bigint,text,text) from public, anon, authenticated;
grant execute on function public.gg_review_request(uuid,bigint,text,text) to service_role;

create or replace function public.gg_get_request_details(p_auth_user_id uuid, p_request_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $details$
declare
  v_membership genomeguard.organization_memberships%rowtype;
  v_request genomeguard.requests%rowtype;
  v_requester_auth uuid;
  v_decision jsonb;
  v_history jsonb;
  v_review_history jsonb;
begin
  if p_auth_user_id is null or p_request_id is null then
    raise exception 'invalid_request_lookup' using errcode = '22023';
  end if;
  select * into v_request from genomeguard.requests where id=p_request_id;
  if not found then
    raise exception 'request_not_found' using errcode = 'P0002';
  end if;
  select m.* into v_membership
  from genomeguard.organization_memberships m
  join genomeguard.organizations o on o.id=m.organization_id
  where m.auth_user_id=p_auth_user_id and m.organization_id=v_request.organization_id
    and m.status='active' and o.status='active'
  limit 1;
  if not found then
    raise exception 'request_not_found' using errcode = 'P0002';
  end if;
  select r.auth_user_id into v_requester_auth
  from genomeguard.requesters r where r.id=v_request.requester_id;
  if v_membership.role='researcher' and v_requester_auth is distinct from p_auth_user_id then
    raise exception 'request_not_found' using errcode = 'P0002';
  end if;
  select case when d.id is null then null else jsonb_build_object(
    'id',d.id,'outcome',d.outcome,'reasons',coalesce(d.reasons_json,'[]')::jsonb,
    'explanation',d.explanation_text,'needs_human',coalesce(d.needs_human,1)=1,
    'reviewed_at',d.reviewed_at
  ) end into v_decision
  from genomeguard.decisions d where d.request_id=p_request_id;
  select coalesce(jsonb_agg(jsonb_build_object(
    'event_type',e.event_type,'outcome',e.outcome,'created_at',e.created_at,'details',e.details
  ) order by e.created_at),'[]'::jsonb) into v_history
  from genomeguard.api_events e where e.request_id=p_request_id and e.auth_user_id is not null;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',h.id,'reviewer_auth_user_id',h.reviewer_auth_user_id,
    'previous_status',h.previous_status,'outcome',h.outcome,'reason',h.reason,
    'decision_id',h.decision_id,'created_at',h.created_at
  ) order by h.created_at,h.id),'[]'::jsonb) into v_review_history
  from genomeguard.request_review_history h where h.request_id=p_request_id;
  return jsonb_build_object(
    'request',jsonb_build_object(
      'id',v_request.id,'created_at',v_request.ts,'purpose',v_request.purpose,
      'disease',v_request.disease,'is_commercial',v_request.is_commercial=1,
      'data_level',v_request.data_level,'status',v_request.status,
      'cohort_filter',v_request.cohort_filter_json::jsonb,
      'variant_filter',v_request.variant_filter_json::jsonb,
      'organization_id',v_request.organization_id
    ),
    'decision',v_decision,'history',v_history,'review_history',v_review_history,
    'release_status','not_released_by_request_detail_api'
  );
end;
$details$;
revoke all on function public.gg_get_request_details(uuid,bigint) from public, anon, authenticated;
grant execute on function public.gg_get_request_details(uuid,bigint) to service_role;